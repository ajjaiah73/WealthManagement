"""Advisory Synthesis Agent.

Neuro-symbolic split:
1. Symbolic pre-screen narrows the catalogue to products the client is eligible
   for at all (no TTR below preservation age or without TTR intent, no closed
   Defined Benefit funds, SMSF only when the client asked about SMSF).
2. Claude (LLMSynthesisAdvisor) chooses among those candidates using the
   fact-find, retrieved evidence, policy thresholds, and any compliance critique.
3. Allocation, fees, disclosures and source citations are copied from the
   product catalogue / retrieval results — never generated by the model.

If the LLM is disabled or any call fails, a deterministic rules-based selector
produces the recommendation instead, so the pipeline never blocks on the LLM.
"""
from dataclasses import dataclass

from app.domain.advisory import AdvisoryRecommendation
from app.domain.client import ClientProfile
from app.domain.product import Product, ProductType
from app.domain.retrieval import RetrievedDocument
from app.services.llm_service import LLMSynthesisAdvisor

DISCLOSURES = [
    "This is general advice only and does not take into account your full personal circumstances.",
    "Refer to the relevant Product Disclosure Statement (PDS) before making a decision.",
]

STANDARD_ASSUMPTIONS = [
    "Client circumstances are as captured in the fact find.",
    "Investment returns are assumed net of fees and taxes unless stated otherwise.",
]

STANDARD_RISKS = [
    "Market volatility may affect projected balances.",
    "Legislative changes to contribution caps or preservation age may occur.",
]

# DEMO_MODE only: pins the *first* draft for named seed clients so the scripted
# demo scenarios (self-correction, fee warning) reproduce reliably. Later
# iterations are always chosen by the synthesis agent itself.
DEMO_SCENARIO_INITIAL_PIN: dict[str, str] = {
    "C-0002": "P-001",  # naive high-growth pick -> triggers self-correction
    "C-0006": "P-013",  # high management-fee choice product -> fee warning
}
# Deterministic-fallback correction for the self-correction scenario.
_FALLBACK_CORRECTED_PIN: dict[str, str] = {"C-0002": "P-010"}


@dataclass
class SynthesisOutcome:
    recommendation: AdvisoryRecommendation
    method: str  # "llm" | "deterministic" | "demo_pin"
    model: str | None
    candidate_ids: list[str]


def eligible_products(profile: ClientProfile, products: list[Product]) -> list[Product]:
    mentions = " ".join(profile.investment_objectives + profile.financial_goals + profile.constraints).lower()
    ttr_eligible = bool(profile.ttr_intent) and profile.age is not None and profile.age >= 60
    eligible: list[Product] = []
    for p in products:
        if p.product_type == ProductType.DEFINED_BENEFIT:
            continue  # closed to new members
        if p.product_type == ProductType.TTR and not ttr_eligible:
            continue
        if p.product_type == ProductType.SMSF and "smsf" not in mentions and "self-managed" not in mentions:
            continue
        eligible.append(p)
    return eligible or list(products)


class AdvisorySynthesisService:
    def __init__(self, llm: LLMSynthesisAdvisor | None = None, demo_mode: bool = True) -> None:
        self._llm = llm
        self._demo_mode = demo_mode

    @property
    def llm_enabled(self) -> bool:
        return self._llm is not None

    def synthesize(
        self,
        profile: ClientProfile,
        products: list[Product],
        retrieved: list[RetrievedDocument],
        critique_notes: list[str],
    ) -> AdvisoryRecommendation:
        return self.synthesize_with_meta(profile, products, retrieved, critique_notes).recommendation

    def synthesize_with_meta(
        self,
        profile: ClientProfile,
        products: list[Product],
        retrieved: list[RetrievedDocument],
        critique_notes: list[str],
        goal: str | None = None,
    ) -> SynthesisOutcome:
        if not products:
            raise ValueError("No products available to synthesize a recommendation")
        by_id = {p.product_id: p for p in products}
        candidates = eligible_products(profile, products)
        candidate_ids = [p.product_id for p in candidates]

        if self._demo_mode and not critique_notes:
            pinned = by_id.get(DEMO_SCENARIO_INITIAL_PIN.get(profile.client_id, ""))
            if pinned is not None:
                rec = self._build(pinned, retrieved, self._rationale(profile, pinned), [])
                return SynthesisOutcome(rec, "demo_pin", None, candidate_ids)

        if self._llm is not None:
            choice = self._llm.choose(profile, goal, candidates, retrieved, critique_notes)
            if choice is not None:
                product = by_id[choice["product_id"]]
                rationale = choice["reasoning"] or self._rationale(profile, product)
                rec = self._build(product, retrieved, rationale, choice["risks"])
                return SynthesisOutcome(rec, "llm", self._llm.model, candidate_ids)

        product = self._deterministic_choice(profile, candidates, by_id, critique_notes)
        rec = self._build(product, retrieved, self._rationale(profile, product), [])
        return SynthesisOutcome(rec, "deterministic", None, candidate_ids)

    def _deterministic_choice(
        self,
        profile: ClientProfile,
        candidates: list[Product],
        by_id: dict[str, Product],
        critique_notes: list[str],
    ) -> Product:
        correction_requested = bool(critique_notes) and any(
            "allocation" in note.lower() or "growth" in note.lower() for note in critique_notes
        )
        candidate: Product | None = None
        if correction_requested:
            candidate = by_id.get(_FALLBACK_CORRECTED_PIN.get(profile.client_id, ""))
        if candidate is None and not correction_requested and self._demo_mode:
            candidate = by_id.get(DEMO_SCENARIO_INITIAL_PIN.get(profile.client_id, ""))
        if candidate is None:
            candidate = self._select_candidate(profile, candidates, conservative_override=correction_requested)
        return candidate or candidates[0]

    @staticmethod
    def _build(
        product: Product, retrieved: list[RetrievedDocument], rationale: str, extra_risks: list[str]
    ) -> AdvisoryRecommendation:
        return AdvisoryRecommendation(
            strategy_name=f"{product.product_name} Strategy",
            product_id=product.product_id,
            product_type=product.product_type.value,
            allocation=product.growth_defensive_split,
            fee_percentage=product.total_fee_pct,
            rationale=rationale,
            assumptions=list(STANDARD_ASSUMPTIONS),
            risks=list(dict.fromkeys(extra_risks + STANDARD_RISKS)),
            source_documents=list(dict.fromkeys(
                [d.document_id for d in retrieved]
                + ([product.source_document_id] if product.source_document_id else [])
            )),
            disclosures=list(DISCLOSURES),
        )

    @staticmethod
    def _select_candidate(
        profile: ClientProfile, products: list[Product], conservative_override: bool = False
    ) -> Product | None:
        general_pool = [p for p in products if p.product_type in (ProductType.MY_SUPER, ProductType.CHOICE)]
        pool = general_pool or products
        risk = profile.risk_tolerance.value if profile.risk_tolerance else "Moderate"

        if profile.ttr_intent and profile.age is not None and profile.age >= 60:
            ttr_products = [p for p in products if p.product_type == ProductType.TTR]
            if ttr_products:
                return ttr_products[0]

        if conservative_override:
            conservative_sorted = sorted(pool, key=lambda p: -AdvisorySynthesisService._defensive_pct(p))
            if conservative_sorted:
                return conservative_sorted[0]

        if risk in ("Growth", "High Growth"):
            growth_products = [p for p in pool if p.product_type == ProductType.CHOICE]
            if growth_products:
                return growth_products[0]

        my_super = [p for p in pool if p.product_type == ProductType.MY_SUPER]
        return my_super[0] if my_super else (pool[0] if pool else None)

    @staticmethod
    def _defensive_pct(product: Product) -> float:
        try:
            _, defensive = product.growth_defensive_split.replace("%", "").split("/")
            return float(defensive.strip())
        except (ValueError, AttributeError):
            return 0.0

    @staticmethod
    def _rationale(profile: ClientProfile, product: Product) -> str:
        risk = profile.risk_tolerance.value if profile.risk_tolerance else "Moderate"
        return (
            f"Selected for a {risk} risk profile at age {profile.age}, "
            f"targeting retirement at {profile.target_retirement_age}."
        )


